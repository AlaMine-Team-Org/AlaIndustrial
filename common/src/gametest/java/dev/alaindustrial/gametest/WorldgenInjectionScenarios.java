	/** The biomes that must carry a feature, resolved in the running world. */
	@FunctionalInterface
	private interface Carriers {
		List<ResourceKey<Biome>> in(GameTestHelper helper);

		/** The same biomes in every world: for features injected by tag or by biome id. */
		static Carriers fixed(List<ResourceKey<Biome>> biomes) {
			return helper -> biomes;
		}
	}

	/** One placed feature: the step it belongs to, biomes that must carry it, biomes that must not. */
	private record Injection(String feature, GenerationStep.Decoration step,
			Carriers carriers, List<ResourceKey<Biome>> bystanders) {}

