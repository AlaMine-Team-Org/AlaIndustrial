	/**
	 * The scenarios above cover every placed feature the mod ships: a thirteenth feature
	 * added to {@code data/alaindustrial/worldgen/placed_feature/} without a row here fails.
	 */
	public static void everyShippedPlacedFeatureHasAnInjectionScenario(GameTestHelper helper) {
		Set<String> shipped = new TreeSet<>();
		for (Identifier id : helper.getLevel().registryAccess().lookupOrThrow(Registries.PLACED_FEATURE).keySet()) {
			if ("alaindustrial".equals(id.getNamespace())) {
				shipped.add(id.getPath());
			}
		}
		Set<String> covered = new TreeSet<>();
		for (Injection injection : ALL) {
			covered.add(injection.feature());
		}
		if (!shipped.equals(covered)) {
			Set<String> uncovered = new TreeSet<>(shipped);
			uncovered.removeAll(covered);
			Set<String> missing = new TreeSet<>(covered);
			missing.removeAll(shipped);
			helper.fail("placed features without an injection scenario: " + uncovered
					+ "; scenario rows whose placed feature is not loaded: " + missing);
			return;
		}
		helper.succeed();
	}

	/**
	 * The overworld biomes both ore selectors take in this world: every biome the overworld's biome
	 * source can generate (what {@code foundInOverworld()} asks) that also carries
	 * {@code #minecraft:is_overworld} (the NeoForge selector), sorted by id for a stable message.
	 */
	private static List<ResourceKey<Biome>> overworldBiomesOfThisWorld(GameTestHelper helper) {
		Registry<Biome> biomes = helper.getLevel().registryAccess().lookupOrThrow(Registries.BIOME);
		Set<ResourceKey<Biome>> found = new TreeSet<>(Comparator.comparing(key -> key.identifier().toString()));
		for (Holder<Biome> holder : helper.getLevel().getServer().overworld().getChunkSource().getGenerator()
				.getBiomeSource().possibleBiomes()) {
			holder.unwrapKey().filter(key -> biomes.getOrThrow(key).is(BiomeTags.IS_OVERWORLD)).ifPresent(found::add);
		}
		return List.copyOf(found);
	}

	/** Collects EVERY mismatch of one feature, so a first run names all of them, not the first only. */
	private static void verify(GameTestHelper helper, Injection injection) {
		ResourceKey<PlacedFeature> feature = BiomeFeatureProbe.placed(injection.feature());
		List<String> problems = new ArrayList<>();
		List<ResourceKey<Biome>> carriers = injection.carriers().in(helper);
		if (carriers.isEmpty()) {
			problems.add("no biome to probe: the overworld of this world generates no biome both selectors take");
		}
		for (ResourceKey<Biome> biome : carriers) {
			List<GenerationStep.Decoration> steps = BiomeFeatureProbe.stepsOf(helper, biome, feature);
			if (!steps.contains(injection.step())) {
				problems.add("not generated in " + biome.identifier() + " at " + injection.step()
						+ " (generated at steps: " + steps + ")");
			}
		}
		for (ResourceKey<Biome> biome : injection.bystanders()) {
			List<GenerationStep.Decoration> steps = BiomeFeatureProbe.stepsOf(helper, biome, feature);
			if (!steps.isEmpty()) {
				problems.add("generated in " + biome.identifier() + " (steps: " + steps
						+ "), which its selector leaves out");
			}
		}
		if (!problems.isEmpty()) {
			helper.fail(injection.feature() + ": " + String.join("; ", problems));
			return;
		}
		helper.succeed();
	}
