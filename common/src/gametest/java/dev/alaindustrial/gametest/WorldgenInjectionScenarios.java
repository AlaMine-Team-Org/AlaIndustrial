/**
 * L2 characterization of worldgen injection (MOD-702, MISC-6): every placed feature the mod ships is
 * generated by the biomes of its selector, at the step its entrance spec names, and by no biome
 * outside it — on BOTH loaders, read back through the same generation settings
 * ({@link BiomeFeatureProbe}).
 *
 * <p>The two loaders inject the same twelve features by different means and by different selectors:
 * Fabric in code ({@code ModWorldGen} → {@code BiomeModifications.addFeature}), NeoForge through eight
 * {@code neoforge/biome_modifier/*.json} files, and no gate compares the two lists. A feature one
 * loader forgot, put on the wrong step or aimed at another selector turns the scenario of that
 * feature red on that loader only. The scenarios pin the CURRENT behaviour; a divergence they find is a
 * defect to be filed, not data to be edited here.
 *
 * <p><b>The ores' biomes are read from the running world, never named.</b> Fabric injects the five ores
 * with {@code BiomeSelectors.foundInOverworld()}, which asks the overworld's own biome source which
 * biomes it can generate; NeoForge takes {@code #minecraft:is_overworld}. The game-test world is a flat
 * overworld of ONE biome, and which one depends on the game version: vanilla {@code GameTestServer}
 * builds {@code WorldPresets.FLAT} (plains) on 26.2 and {@code FLAT_ALL_DIMENSIONS} (desert) on 26.3.
 * A named biome the world cannot generate is left out by Fabric with no defect, so the ores are
 * probed in every biome the overworld of THIS world can generate that also carries
 * {@code #minecraft:is_overworld} — the biomes both selectors take ({@link #overworldBiomesOfThisWorld}).
 * That set must not be empty, so a forgotten ore cannot pass for want of a biome to ask. The selector
 * difference itself (a modded overworld biome the Fabric selector misses) cannot be seen from here.
 *
 * <p>Biomes outside a selector are probed at EVERY step, not only at the feature's own: a feature on a
 * second step is as wrong as one in a second biome.
 */
